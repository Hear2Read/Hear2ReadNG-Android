data class TextChunk(
    var text: String,
    val isEnglish: Boolean
)

/***
 * Holds the parameters required by the H2RNG engine for synthesis
 *
 * @property speed Rate of speech, 0f..1f
 * @property pitch Pitch of speech, 0f..1f
 * @property volume Volume, 0..100, unused currently
 * @property charMode Character mode, unused
 * @property sampleRate Desired samplerate of output, determined by the samplerate of the English
 * TTS
 */
data class SpeechParams(
    val speed: Float = 1.0f,
    val pitch: Float = 1.0f,
    val volume: Int = 100,
    val charMode: Boolean = false,
    val sampleRate: Int = 24000 // Samplerate
)

/**
 * TTS engine interface to be used with [TtsPipeline]. Requires only synthesis, stopping synthesis
 * and shutting down functionality to be implemented
 *
 */
interface TtsEngine {
    fun synthesize(text: String, params: SpeechParams): ReceiveChannel<ByteArray>
    fun stop()
    fun shutdown()
}

/**
 * Interface to consume audio generated by the [TtsEngine]s in the [TtsPipeline].
 *
 */
interface AudioOutput {
    fun start(sampleRate: Int)
    fun write(audio: ByteArray): Boolean
    fun done()
}

